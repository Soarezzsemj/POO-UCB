package br.com.controle;



// isso é um metodo(função com nome diferente)
public class Dobro {

    //variavel -> atributo
    //função -> metodo

    private double valor;

    public void setValor(double valor){
        this.valor = valor;
    }

    public double getValor(){
        return this.valor = valor;
    }

    public double getDobroValor(){
        return this.valor*2;
    }


}
